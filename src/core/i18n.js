function translateComposite(value) {
  for (const separator of [" · ", " / ", " → ", " | "]) {
    if (!value.includes(separator)) continue;
    const parts = value.split(separator);
    const translated = parts.map((part) => translateText(part, "en"));
    if (translated.some((part, index) => part !== parts[index])) return translated.join(separator);
  }
  return value;
}

export function normalizeLanguage(language = "fr") {
  const code = String(language).trim().toLowerCase().split(/[-_]/)[0];
  return supportedLanguages.includes(code) ? code : "fr";
}

export function translateText(value, language = "fr") {
  if (normalizeLanguage(language) === "fr" || value == null) return String(value ?? "");
  const source = String(value);
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  const core = source.slice(leading.length, source.length - trailing.length || undefined);
  if (!core) return source;
  if (en[core]) return `${leading}${en[core]}${trailing}`;
  const normalizedSpaces = core.replace(/\u00a0/g, " ");
  if (en[normalizedSpaces]) return `${leading}${en[normalizedSpaces]}${trailing}`;
  if (normalizedSpaces.startsWith("« ") && normalizedSpaces.endsWith(" »")) {
    const inner = normalizedSpaces.slice(2, -2);
    const translated = translateText(inner, "en");
    if (translated !== inner) return `${leading}“${translated}”${trailing}`;
  }
  if (normalizedSpaces.startsWith("✓ ")) {
    const inner = normalizedSpaces.slice(2);
    const translated = translateText(inner, "en");
    if (translated !== inner) return `${leading}✓ ${translated}${trailing}`;
  }
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(normalizedSpaces)) return `${leading}${normalizedSpaces.replace(pattern, replacement)}${trailing}`;
  }
  const composite = translateComposite(core);
  return `${leading}${composite}${trailing}`;
}

export function localizeElement(root, language = "fr") {
  const locale = normalizeLanguage(language);
  document.documentElement.lang = locale;
  if (!root) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      return node.parentElement?.closest("script, style") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (!sourceText.has(node)) sourceText.set(node, node.nodeValue);
    const source = sourceText.get(node);
    node.nodeValue = locale === "fr" ? source : translateText(source, locale);
  });

  const elements = root.matches?.("*") ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
  elements.forEach((element) => {
    if (!sourceAttributes.has(element)) sourceAttributes.set(element, new Map());
    const originals = sourceAttributes.get(element);
    translatableAttributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      if (!originals.has(attribute)) originals.set(attribute, element.getAttribute(attribute));
      const source = originals.get(attribute);
      element.setAttribute(attribute, locale === "fr" ? source : translateText(source, locale));
    });
  });
}

export function languageName(language, displayLanguage = language) {
  const code = normalizeLanguage(language);
  if (normalizeLanguage(displayLanguage) === "en") return code === "fr" ? "French" : "English";
  return code === "fr" ? "Français" : "Anglais";
}
